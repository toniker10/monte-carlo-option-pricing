def black_scholes_call(S0, K, T, r, sigma):
    d1 = (np.log(S0 / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    price = S0 * si.norm.cdf(d1) - K * np.exp(-r * T) * si.norm.cdf(d2)
    return price

def mc_pure_python(S0, K, T, r, sigma, n_sim, seed):
    rng = np.random.default_rng(seed)
    payoff_sum = 0.0
    drift = (r - 0.5 * sigma ** 2) * T
    vol = sigma * np.sqrt(T)
    normals = rng.standard_normal(n_sim)
    for i in range(n_sim):
        z = normals[i]
        ST = S0 * np.exp(drift + vol * z)
        payoff = max(ST - K, 0.0)
        payoff_sum += payoff
    price = np.exp(-r * T) * (payoff_sum / n_sim)
    return price

def mc_numpy_vectorized(S0, K, T, r, sigma, n_sim, seed):
    rng = np.random.default_rng(seed)
    Z = rng.standard_normal(n_sim)
    ST = S0 * np.exp((r - 0.5 * sigma ** 2) * T + sigma * np.sqrt(T) * Z)
    payoff = np.maximum(ST - K, 0.0)
    price = np.exp(-r * T) * np.mean(payoff)
    return price

from numba import jit, prange

@jit(nopython=True, cache=True)
def mc_numba_jit(S0, K, T, r, sigma, n_sim, seed):
    np.random.seed(seed)
    payoff_sum = 0.0
    drift = (r - 0.5 * sigma ** 2) * T
    vol = sigma * np.sqrt(T)
    for i in range(n_sim):
        z = np.random.normal()
        ST = S0 * np.exp(drift + vol * z)
        payoff = max(ST - K, 0.0)
        payoff_sum += payoff
    price = np.exp(-r * T) * (payoff_sum / n_sim)
    return price

@jit(nopython=True, parallel=True, cache=True)
def mc_numba_parallel(S0, K, T, r, sigma, n_sim, seed):
    np.random.seed(seed)
    drift = (r - 0.5 * sigma ** 2) * T
    vol = sigma * np.sqrt(T)
    payoff_sum = 0.0
    for i in prange(n_sim):
        z = np.random.normal()
        ST = S0 * np.exp(drift + vol * z)
        payoff = max(ST - K, 0.0)
        payoff_sum += payoff
    price = np.exp(-r * T) * (payoff_sum / n_sim)
    return price

